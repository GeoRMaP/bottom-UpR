#' List bottom-UpR warning messages and recommended actions
#'
#' Returns the package-level warning messages/patterns that can be emitted by
#' bottom-UpR itself. Dynamic fields are shown in braces. Warnings originating
#' internally from INLA are not reproduced, although bottom-UpR warnings about
#' INLA diagnostics are included.
#'
#' @return A data frame with warning identifier, category, message pattern,
#'   trigger, and suggested action.
#' @export
bottom_up_warning_catalogue <- function() {
  data.frame(
    warning_id=c(
      "coordinates_geographic","sparse_hierarchy","missing_values",
      "response_override","count_no_buildings","ppb_no_buildings",
      "adaptive_mesh_edge_order","mesh_edge_order","mesh_cutoff_large",
