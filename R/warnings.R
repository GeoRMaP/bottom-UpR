    trigger=c(
      "Coordinate names/values look geographic in a distance-based spatial workflow.",
      "A hierarchical grouping has at least one level with fewer than 3 records.",
      "Required model/prediction columns contain NA values.",
      "Explicit response_type differs from automatic detection.",
      "COUNT response is specified without buildings.",
      "PPB response is specified without buildings.",
      "Adaptive inner_edge_fraction produces max_edge[1] >= max_edge[2].",
      "Explicit max_edge[1] >= max_edge[2].",
      "cutoff > max_edge[1].",
      "INLA returns positive CPO failure indicators.",
      "INLA returns a non-zero optimization mode status.",
      "The best automatic likelihood score is non-finite.",
      "The selector receives no candidate covariates.",
      "Candidate names cannot be matched to INLA fixed-effect summaries.",
      "No interval excludes zero and fallback > 0.",
      "At least one holdout fold has fewer than 3 rows.",
      "A fold-specific selector returns no retained covariates.",
      "Held-out prediction means contain non-finite values.",
      "Moran input contains non-finite coordinates/observed/predicted values.",
      "A requested Moran distance threshold has no neighbour links.",
      "chunkwise=TRUE and chunk_size >= nrow(newdata).",
      "nrow(newdata) * draws > 50,000,000 with return_draws=TRUE.",
      "Prediction buildings contain NA/Inf.",
      "Prediction buildings contain negative values.",
      "Aggregation group contains NA.",
      "Posterior draw matrix contains NA/Inf.",
      "Synthetic n < 50.",
      "chunkwise simulation is requested with chunk_size >= n."
    ),
    suggested_action=c(
      "Project coordinates and use matching distance units.",
      "Combine sparse levels, simplify the hierarchy, or interpret cautiously.",
