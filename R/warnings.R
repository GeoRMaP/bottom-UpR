      "Missing values detected in: {columns}. INLA/model functions may drop or fail on incomplete rows; preprocess explicitly.",
      "response_type='{requested}' overrides automatic detection ('{detected}').",
      "COUNT model has no building exposure column; the model will not include a log(buildings) offset.",
      "PPB model has no buildings column; population reconstruction from PPB will not be available automatically.",
      "Adaptive inner max_edge is not smaller than outer max_edge.",
      "Inner max_edge is not smaller than outer max_edge; check mesh settings.",
      "cutoff exceeds inner max_edge; this may over-thin input locations.",
      "INLA reported CPO failures for some observations; inspect fit$cpo$failure.",
      "INLA optimization returned a non-zero mode status; inspect fit$mode.",
      "Likelihood comparison produced non-finite mean log CPO scores.",
      "No candidate covariates supplied; selector returns an empty set.",
      "None of the candidate covariates were found in INLA fixed-effect summaries; returning all candidates.",
      "No candidate credible intervals excluded zero; applying fallback and retaining the strongest {fallback} effect(s).",
      "Some validation folds contain fewer than 3 held-out observations; metrics may be unstable.",
      "Fold {fold} selected zero covariates; fitting an intercept/spatial/hierarchical model.",
      "Non-finite held-out predictions were produced; inspect fold-level results.",
      "Non-finite held-out records are excluded from Moran's I calculation.",
      "One or more Moran distance bands contain no neighbour links.",
      "chunkwise=TRUE but chunk_size is at least nrow(newdata); prediction will use one chunk.",
