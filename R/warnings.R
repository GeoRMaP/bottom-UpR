      "Inspect INLA optimization diagnostics and refit if needed.",
      "Inspect candidate fits rather than relying on automatic selection.",
      "Supply candidate covariates or skip selection deliberately.",
      "Check covariate names and fixed-effect construction.",
      "Review the selector/fallback rule.",
      "Change the fold design or interpret unstable fold metrics cautiously.",
      "Confirm that a no-covariate fold model is acceptable.",
      "Inspect fold predictions and model convergence.",
      "Correct/exclude invalid held-out records.",
      "Increase thresholds or inspect sampling geometry.",
      "Reduce chunk_size to demonstrate/use multiple chunks.",
      "Use return_draws=FALSE and aggregate_by= for large grids.",
      "Correct non-finite exposure; structural-zero handling is a safeguard.",
      "Correct invalid negative exposure values.",
      "Supply complete group labels or accept exclusion.",
      "Inspect and correct the source posterior draws.",
      "Increase n for spatial/CV demonstrations.",
      "Use a smaller chunk_size."
    ),
    stringsAsFactors=FALSE
  )
}
